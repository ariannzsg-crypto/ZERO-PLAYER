/**
 * Release signing is read from a local, git-ignored `keystore.properties`.
 * When it is absent (fresh clone / CI without secrets) the release build falls
 * back to the debug key so that `assembleRelease` still produces an installable
 * APK. No secret material is ever committed to the repository.
 */
val keystorePropsFile = rootProject.file("keystore.properties")
val keystoreProps = Properties().apply {
    if (keystorePropsFile.exists()) keystorePropsFile.inputStream().use { load(it) }
}

