                "META-INF/version-control-info.textproto",
            )
        }
    }

    applicationVariants.all {
        outputs.all {
            val output = this as com.android.build.gradle.internal.api.BaseVariantOutputImpl
            output.outputFileName = "ZERO-PLAYER-${versionName}-${name}.apk"
        }
    }

